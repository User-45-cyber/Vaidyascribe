"""
VaidyaScribe — PDF Export Route
POST /api/export/pdf — generates a professional clinical PDF from session data.
"""

import io
from fastapi import APIRouter, HTTPException
from fastapi.responses import StreamingResponse
from pydantic import BaseModel
from typing import Optional
from datetime import datetime

from fpdf import FPDF

router = APIRouter()


class ExportRequest(BaseModel):
    session_id: Optional[str] = None
    clinic_name: Optional[str] = "VaidyaScribe Clinic"
    doctor_name: Optional[str] = "Dr. Demo"
    registration_number: Optional[str] = ""
    patient_ref: Optional[str] = ""
    date: Optional[str] = None
    soap: Optional[dict] = None
    transcript: Optional[str] = ""


class VaidyaPDF(FPDF):
    def __init__(self, clinic_name, doctor_name, reg_number):
        super().__init__()
        self.clinic_name = clinic_name
        self.doctor_name = doctor_name
        self.reg_number = reg_number

    def header(self):
        self.set_font("Helvetica", "B", 18)
        self.set_text_color(29, 158, 117)  # #1D9E75
        self.cell(0, 10, self.clinic_name, new_x="LMARGIN", new_y="NEXT", align="L")

        self.set_font("Helvetica", "", 10)
        self.set_text_color(80, 80, 80)
        doctor_line = self.doctor_name
        if self.reg_number:
            doctor_line += f"  |  Reg: {self.reg_number}"
        self.cell(0, 6, doctor_line, new_x="LMARGIN", new_y="NEXT", align="L")

        self.set_draw_color(229, 231, 235)
        self.line(10, self.get_y() + 2, 200, self.get_y() + 2)
        self.ln(6)

    def footer(self):
        self.set_y(-20)
        self.set_font("Helvetica", "I", 7)
        self.set_text_color(150, 150, 150)
        self.cell(
            0,
            10,
            "Generated by VaidyaScribe - AI-assisted draft. Review and verify before use.",
            new_x="LMARGIN",
            new_y="NEXT",
            align="C",
        )


@router.post("/api/export/pdf")
async def export_pdf(req: ExportRequest):
    if not req.soap:
        raise HTTPException(status_code=400, detail="SOAP data is required for PDF export.")

    pdf = VaidyaPDF(
        clinic_name=req.clinic_name or "VaidyaScribe Clinic",
        doctor_name=req.doctor_name or "Dr. Demo",
        reg_number=req.registration_number or "",
    )
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=25)

    # Date
    date_str = req.date or datetime.now().strftime("%d %B %Y, %I:%M %p")
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(107, 114, 128)
    pdf.cell(0, 6, f"Date: {date_str}", new_x="LMARGIN", new_y="NEXT", align="R")
    pdf.ln(2)

    # Patient ref
    if req.patient_ref:
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(26, 26, 46)
        pdf.cell(0, 7, f"Patient Reference: {req.patient_ref}", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(3)

    # SOAP sections
    sections = [
        ("SUBJECTIVE", req.soap.get("subjective", "")),
        ("OBJECTIVE", req.soap.get("objective", "")),
        ("ASSESSMENT", req.soap.get("assessment", "")),
        ("PLAN", req.soap.get("plan", "")),
    ]

    for title, content in sections:
        # Section heading
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(29, 158, 117)
        pdf.cell(0, 8, title, new_x="LMARGIN", new_y="NEXT")

        # Section body
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(26, 26, 46)
        body = content if content else "Not documented in this encounter."
        pdf.multi_cell(0, 5.5, body)
        pdf.ln(4)

    # Output to bytes
    pdf_bytes = pdf.output()
    buffer = io.BytesIO(pdf_bytes)
    buffer.seek(0)

    filename = f"vaidyascribe_{req.session_id or 'note'}.pdf"

    return StreamingResponse(
        buffer,
        media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )
