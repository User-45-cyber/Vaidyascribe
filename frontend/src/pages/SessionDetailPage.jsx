import { useState, useEffect } from 'react';
import { useParams, useNavigate } from 'react-router-dom';
import { apiGet, apiPost, apiDelete } from '../api/client';
import { useAuth } from '../contexts/AuthContext';
import Navbar from '../components/Navbar';
import LoadingSpinner from '../components/LoadingSpinner';

export default function SessionDetailPage() {
  const { id } = useParams();
  const navigate = useNavigate();
  const { user } = useAuth();
  const [session, setSession] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  useEffect(() => {
    (async () => {
      try {
        const data = await apiGet(`/api/sessions/${id}`);
        setSession(data);
      } catch (err) {
        setError(err.message);
      } finally {
        setLoading(false);
      }
    })();
  }, [id]);

  const handleExportPDF = async () => {
    try {
      const blob = await apiPost('/api/export/pdf', {
        session_id: id,
        clinic_name: user?.clinic_name || 'VaidyaScribe Clinic',
        doctor_name: user?.full_name || 'Dr. Demo',
        registration_number: user?.registration_number || '',
        patient_ref: session?.patient_ref || '',
        soap: {
          subjective: session?.soap_subjective || '',
          objective: session?.soap_objective || '',
          assessment: session?.soap_assessment || '',
          plan: session?.soap_plan || '',
        },
      });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `vaidyascribe_${id}.pdf`;
      a.click();
      URL.revokeObjectURL(url);
    } catch (err) {
      alert('PDF export failed: ' + err.message);
    }
  };

  const handleExportTXT = () => {
    const text = [
      `VaidyaScribe — Clinical Note`,
      `Date: ${session?.created_at || ''}`,
      `Patient Ref: ${session?.patient_ref || 'N/A'}`,
      `Language: ${session?.language || 'auto'}`,
      ``,
      `=== TRANSCRIPT ===`,
      session?.transcript || '',
      ``,
      `=== SOAP NOTE ===`,
      ``,
      `SUBJECTIVE:`,
      session?.soap_subjective || 'Not documented.',
      ``,
      `OBJECTIVE:`,
      session?.soap_objective || 'Not documented.',
      ``,
      `ASSESSMENT:`,
      session?.soap_assessment || 'Not documented.',
      ``,
      `PLAN:`,
      session?.soap_plan || 'Not documented.',
      ``,
      `---`,
      `Generated by VaidyaScribe — AI-assisted draft. Review and verify before use.`,
    ].join('\n');

    const blob = new Blob([text], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `vaidyascribe_${id}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleDelete = async () => {
    if (!window.confirm('Are you sure you want to delete this session?')) return;
    try {
      await apiDelete(`/api/sessions/${id}`);
      navigate('/dashboard');
    } catch (err) {
      alert('Delete failed: ' + err.message);
    }
  };

  if (loading) return (
    <div>
      <Navbar />
      <div className="page-container"><LoadingSpinner text="Loading session..." /></div>
    </div>
  );

  if (error) return (
    <div>
      <Navbar />
      <div className="page-container">
        <div style={{ textAlign: 'center', padding: '4rem' }}>
          <p style={{ color: 'var(--color-danger)' }}>Error: {error}</p>
          <button className="btn btn-secondary" onClick={() => navigate('/dashboard')}>
            Back to Dashboard
          </button>
        </div>
      </div>
    </div>
  );

  const soapSections = [
    { key: 'soap_subjective', label: 'Subjective', color: '#3B82F6' },
    { key: 'soap_objective', label: 'Objective', color: '#8B5CF6' },
    { key: 'soap_assessment', label: 'Assessment', color: '#F59E0B' },
    { key: 'soap_plan', label: 'Plan', color: '#10B981' },
  ];

  return (
    <div className="session-detail-root" style={{ minHeight: '100vh', backgroundColor: 'var(--bg-body)' }}>
      <Navbar />
      <div style={{ padding: '2.5rem', maxWidth: '1400px', margin: '0 auto' }}>
        <header style={{ marginBottom: '3rem', display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start' }}>
          <div>
            <div style={{ display: 'flex', alignItems: 'center', gap: '0.75rem', marginBottom: '0.75rem' }}>
              <button 
                onClick={() => navigate('/dashboard')}
                style={{ background: 'white', border: '1px solid var(--border-light)', borderRadius: '10px', padding: '0.4rem 0.8rem', color: 'var(--text-secondary)', fontWeight: 700, cursor: 'pointer', fontSize: '0.85rem' }}
              >
                ← Back
              </button>
              <span style={{ fontSize: '0.8rem', fontWeight: 800, color: 'var(--brand-primary)', textTransform: 'uppercase', letterSpacing: '0.05em' }}>
                Consultation Archive
              </span>
            </div>
            <h1 style={{ fontSize: '2.25rem', fontWeight: 900, color: 'var(--text-primary)', marginBottom: '0.5rem', letterSpacing: '-0.02em' }}>
              {session?.patient_ref || 'Patient Consultation'}
            </h1>
            <p style={{ color: 'var(--text-secondary)', fontSize: '1rem', fontWeight: 500 }}>
              {session?.created_at ? new Date(session.created_at).toLocaleDateString('en-IN', {
                day: '2-digit', month: 'long', year: 'numeric', hour: '2-digit', minute: '2-digit'
              }) : ''}
              <span style={{ margin: '0 0.75rem', opacity: 0.3 }}>|</span>
              ID: #{id.slice(0, 8)}
            </p>
          </div>
          <div style={{ display: 'flex', gap: '1rem' }}>
            <button className="btn btn-outline" style={{ padding: '0.75rem 1.5rem', borderRadius: '12px' }} onClick={handleExportPDF}>📄 Export PDF</button>
            <button className="btn btn-outline" style={{ padding: '0.75rem 1.5rem', borderRadius: '12px' }} onClick={handleExportTXT}>📝 Text File</button>
            <button className="btn" style={{ padding: '0.75rem 1.5rem', borderRadius: '12px', background: '#FEF2F2', color: '#B91C1C', border: 'none', fontWeight: 700 }} onClick={handleDelete}>🗑 Delete</button>
          </div>
        </header>

        <div style={{ display: 'grid', gridTemplateColumns: '1.2fr 2fr', gap: '2rem' }}>
          {/* Transcript Panel */}
          <section style={{ background: 'white', border: '1px solid var(--border-light)', borderRadius: '24px', boxShadow: 'var(--shadow-premium)', overflow: 'hidden' }}>
            <div style={{ padding: '1.5rem 2rem', background: '#F8FAFC', borderBottom: '1px solid var(--border-light)', display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
              <h3 style={{ fontSize: '1rem', fontWeight: 800 }}>📜 Interaction Transcript</h3>
              <span style={{ background: '#F1F5F9', color: '#64748B', padding: '0.3rem 0.7rem', borderRadius: '6px', fontSize: '0.75rem', fontWeight: 800 }}>
                {session?.language?.toUpperCase() || 'AUTO'}
              </span>
            </div>
            <div style={{ padding: '2rem' }}>
              <div style={{ 
                lineHeight: 1.8, color: 'var(--text-secondary)', fontSize: '0.95rem', 
                whiteSpace: 'pre-wrap', maxHeight: '700px', overflowY: 'auto',
                paddingRight: '1rem'
              }}>
                {session?.transcript || 'No transcript available for this session.'}
              </div>
            </div>
          </section>

          {/* SOAP Note Panel */}
          <section style={{ background: 'white', border: '1px solid var(--border-light)', borderRadius: '24px', boxShadow: 'var(--shadow-premium)', overflow: 'hidden' }}>
            <div style={{ padding: '1.5rem 2rem', background: '#F8FAFC', borderBottom: '1px solid var(--border-light)', display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
              <h3 style={{ fontSize: '1rem', fontWeight: 800 }}>🩺 Clinical SOAP Note</h3>
              <span style={{ background: '#ECFDF5', color: '#059669', padding: '0.35rem 0.85rem', borderRadius: '99px', fontSize: '0.8rem', fontWeight: 800 }}>
                {session?.status === 'approved' ? '✓ VERIFIED' : (session?.status?.toUpperCase() || 'DRAFT')}
              </span>
            </div>
            <div style={{ padding: '2.5rem' }}>
              {soapSections.map(({ key, label, color }) => (
                <div key={key} style={{ marginBottom: '2.5rem' }}>
                  <div style={{ display: 'flex', alignItems: 'center', gap: '0.75rem', marginBottom: '1rem' }}>
                    <div style={{ width: '4px', height: '20px', background: color, borderRadius: '4px' }}></div>
                    <h4 style={{ fontSize: '0.85rem', fontWeight: 900, textTransform: 'uppercase', letterSpacing: '0.1em', color: 'var(--text-tertiary)' }}>
                      {label}
                    </h4>
                  </div>
                  <div style={{ 
                    padding: '1.25rem 1.5rem', background: '#F8FAFC', borderRadius: '16px',
                    border: '1px solid var(--border-light)', color: 'var(--text-primary)',
                    fontSize: '1rem', lineHeight: 1.7, whiteSpace: 'pre-wrap'
                  }}>
                    {session?.[key] || 'Data not recorded in this section.'}
                  </div>
                </div>
              ))}
            </div>
          </section>
        </div>
      </div>
    </div>
  );
}
